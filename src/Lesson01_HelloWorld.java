// УРОК 1. JDK и Hello World
public class Lesson01_HelloWorld {
    public static void main(String[] args) {
        // println печатает текст и переходит на новую строку
        System.out.println("Hello, World!");

        // print печатает БЕЗ перехода на новую строку
        System.out.print("Привет, ");
        System.out.print("Java!");
        System.out.println(); // пустой println просто переводит строку

        // ЗАДАНИЕ: выведи своё имя и возраст двумя отдельными строками
    }
}
